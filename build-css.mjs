// Builds src/app.css from the component sources in src-css/.
//   node build-css.mjs            minified output  -> src/app.css
//   node build-css.mjs --pretty   readable output  -> src/app.css (for diffing / debugging)
//   node build-css.mjs --out F    write somewhere else
// Order: the numbered files of src-css/ first, then overrides-1/, overrides-2/ ... (rules that must stay behind rules of
// components further down the list). The one dependency, postcss, lives in tools/ (cd tools && npm install).
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(path.join(here, "tools", "package.json"));
const postcss = require("postcss");
const args = process.argv.slice(2);
const src = path.join(here, "src-css");
const out = path.resolve(args.includes("--out") ? args[args.indexOf("--out") + 1] : path.join(here, "src", "app.css"));

const css = (d) => fs.readdirSync(d).filter((f) => f.endsWith(".css")).sort().map((f) => path.join(d, f));
const layers = fs.readdirSync(src, { withFileTypes: true }).filter((e) => e.isDirectory() && /^overrides-\d+$/.test(e.name))
  .sort((a, b) => parseInt(a.name.slice(10)) - parseInt(b.name.slice(10))).map((e) => path.join(src, e.name));
const files = [...css(src), ...layers.flatMap(css)];
const joined = files.map((f) => fs.readFileSync(f, "utf8")).join("\n");

// Minifier: drops comments and layout whitespace, keeps every value as written (no rewriting of numbers or colours).
function minify(source) {
  const root = postcss.parse(source);
  root.walkComments((c) => c.remove());
  const val = (v) => v.replace(/("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'|url\([^)]*\))|\s*,\s*|\s+/g, (m, keep) => (keep ? keep : m.includes(",") ? "," : " ")).replace(/\(\s+/g, "(").replace(/\s+\)/g, ")").trim();
  root.walk((n) => {
    n.raws = {};
    if (n.type === "decl") { n.value = val(n.value); n.raws.between = n.value === "" && n.prop.startsWith("--") ? ": " : ":"; n.raws.important = n.important ? "!important" : ""; }
    else if (n.type === "rule") { n.selector = n.selectors.map((s) => s.replace(/\s+/g, " ").trim()).join(","); n.raws.between = ""; n.raws.semicolon = false; }
    else if (n.type === "atrule") { n.params = n.params.replace(/\s+/g, " ").replace(/\s*([:,])\s*/g, "$1").replace(/\(\s+/g, "(").replace(/\s+\)/g, ")").trim(); n.raws.afterName = n.params ? " " : ""; n.raws.between = ""; n.raws.semicolon = false; }
  });
  return root.toString();
}
let result = joined;
if (!args.includes("--pretty")) result = minify(joined);

const banner = "/* Basalt stylesheet. Generated by build-css.mjs from src-css/, do not edit this file. */\n";
fs.writeFileSync(out, banner + result + "\n");
console.log(`${files.length} files, ${joined.length} bytes of source -> ${out} (${fs.statSync(out).size} bytes)`);

